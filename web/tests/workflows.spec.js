import { test, expect } from '@playwright/test'

const screenshots = process.env.RIDESYNC_SCREENSHOTS || '../docs/design/screenshots'
async function capture(page, name) {
  await page.locator('h1').focus()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: screenshots + '/' + name, fullPage: true })
}

async function choose(page, label, search, name) {
  await page.getByRole('button', { name: new RegExp('^' + label + ':') }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox').fill(search)
  await dialog.getByRole('button', { name: new RegExp(name) }).click()
  await expect(dialog).toBeHidden()
}
async function navigate(page, title) {
  await page.getByRole('navigation').getByRole('button', { name: title, exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
}
async function booking(page, fare) {
  await choose(page, 'Active vehicle', 'TS-DEMO-00', 'TS-DEMO-00')
  await page.getByLabel('Demo fare (INR)').fill(fare)
  await page.getByRole('button', { name: 'Review booking', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm booking', exact: true }).click()
}

